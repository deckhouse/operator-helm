// The layout `helm repo index` writes: the dash of a version sits under the chart name.
const testHelmLayoutIndex = `---
# generated by helm
apiVersion: v1
entries:
  "quoted chart":
  - version: 1.0.0
    digest: abc
    urls:
    - https://example.invalid/quoted-1.0.0.tgz
  empty: []
  podinfo:
  - apiVersion: v2
    description: |
      a block scalar
      # not a comment
    version: 6.7.1
    icon: https://example.invalid/icon.png

    removed: true
# a comment at the margin
  - version: 6.7.0
    maintainers:
    - name: someone
      email: someone@example.invalid
  inline: [{version: 2.0.0, digest: inline}]
generated: "2026-10-16T00:00:00Z"
serverInfo:
  contextPath: /charts
`

func TestDecodeIndexMatchesAWholeDecode(t *testing.T) {
	for name, index := range map[string]string{
		"helm layout":     testHelmLayoutIndex,
		"nested layout":   testIndex,
		"nested urls":     testHybridIndex,
		"crlf":            strings.ReplaceAll(testHelmLayoutIndex, "\n", "\r\n"),
		"no entries":      "apiVersion: v1\ngenerated: now\n",
		"null entries":    "apiVersion: v1\nentries: null\n",
		"empty entries":   "apiVersion: v1\nentries: {}\n",
		"entries first":   "entries:\n  a:\n  - version: 1.0.0\napiVersion: v1\n",
		"no api version":  "entries:\n  a:\n  - version: 1.0.0\n",
		"second document": testIndex + "---\napiVersion: v1\nentries: {}\n",
		"empty first doc": "---\n---\n" + testIndex,
		"marker comment":  "--- # helm\n" + testIndex,
		"indented root":   "  apiVersion: v1\n  entries:\n    a:\n    - version: 1.0.0\n",
		"numeric version": "apiVersion: 1\nentries: null\n",
	} {
		t.Run(name, func(t *testing.T) {
			var want HelmRepositoryIndex
			if err := yaml.Unmarshal([]byte(index), &want); err != nil {
				t.Fatalf("the fixture must decode whole: %v", err)
			}

			got, err := decodeIndex([]byte(index))
			if err != nil {
				t.Fatalf("decodeIndex: %v", err)
			}
			if !reflect.DeepEqual(got, want) {
				t.Fatalf("decodeIndex = %#v, want %#v", got, want)
			}
		})
	}
}

func TestDecodeIndexKeepsItsPeakSmall(t *testing.T) {
	var index bytes.Buffer

	// One chart, so only the batching inside a chart keeps the peak down.
	index.WriteString("apiVersion: v1\nentries:\n  chart:\n")

	for i := 0; index.Len() < 4<<20; i++ {
		fmt.Fprintf(&index, "  - version: 1.0.%d\n    urls: [a]\n", i)
	}

	runtime.GC()

	var peak atomic.Uint64

	done := make(chan struct{})
	sampled := make(chan struct{})

	go func() {
		defer close(sampled)

		for {
			var stats runtime.MemStats

			runtime.ReadMemStats(&stats)

			if stats.HeapInuse > peak.Load() {
				peak.Store(stats.HeapInuse)
			}

			select {
			case <-done:
				return
			case <-time.After(time.Millisecond):
			}
		}
	}()

	got, err := decodeIndex(index.Bytes())

	close(done)
	<-sampled

	if err != nil {
		t.Fatalf("decodeIndex: %v", err)
	}
	if len(got.Entries["chart"]) < 100000 {
		t.Fatalf("expected the chart to carry every version, got %d", len(got.Entries["chart"]))
	}

	// A whole decode of this index holds a heap some fifty times its size.
	t.Logf("decoding held %d MiB for a %d MiB index", peak.Load()>>20, index.Len()>>20)

	if limit := uint64(index.Len()) * 20; peak.Load() > limit {
		t.Fatalf("decoding held %d MiB for a %d MiB index, want at most %d MiB", peak.Load()>>20, index.Len()>>20, limit>>20)
	}
}

// paddingCharts returns enough one-version charts to carry an index past the whole-decode size.
func paddingCharts() string {
	var pad strings.Builder

	for i := 0; pad.Len() <= maxWholeIndexSize; i++ {
		fmt.Fprintf(&pad, "  pad-%d:\n  - version: 1.0.0\n", i)
	}

	return pad.String()
}

func TestDecodeIndexBoundsOneEntry(t *testing.T) {
	entryBefore := maxIndexEntrySize
	maxIndexEntrySize = 256
	t.Cleanup(func() { maxIndexEntrySize = entryBefore })

	for name, entry := range map[string]string{
		"many short lines": "  - version: 1.0.0\n    urls:\n" + strings.Repeat("    - https://example.invalid/x\n", 20),
		"comment lines":    "  - version: 1.0.0\n" + strings.Repeat("#\n", 200),
		"one long line":    "  - version: 1.0.0\n    description: " + strings.Repeat("x", 300) + "\n",
	} {
		t.Run(name, func(t *testing.T) {
			index := "apiVersion: v1\nentries:\n  big:\n" + entry + paddingCharts()

			_, err := decodeIndex([]byte(index))
			if !errors.Is(err, errIndexTooLarge) || !strings.Contains(err.Error(), "big") {
				t.Fatalf("expected an oversize version to be named and refused, got %v", err)
			}

			// Below the whole-decode size any layout is accepted, this version included.
			if _, err := decodeIndex([]byte("apiVersion: v1\nentries:\n  big:\n" + entry)); err != nil {
				t.Fatalf("a small index must be decoded whole instead, got %v", err)
			}
		})
	}
}

func TestDecodeIndexRefusesWhatAWholeDecodeRefuses(t *testing.T) {
	for name, index := range map[string]string{
		"duplicate chart":   "apiVersion: v1\nentries:\n  a:\n  - version: 1.0.0\n  a:\n  - version: 2.0.0\n",
		"duplicate entries": "apiVersion: v1\nentries:\n  a:\n  - version: 1.0.0\nentries: {}\n",
		"broken trailer":    "apiVersion: v1\nentries:\n  a:\n  - version: 1.0.0\nserverInfo:\n  invalid: [\n",
		"flow entries":      "apiVersion: v1\nentries: {a: [{version: 1.0.0}]}\n",
		"list api version":  "apiVersion: [v1]\nentries: {}\n",
		"inline then block": "apiVersion: v1\nentries:\n  a: [{version: 0.1.0}]\n  - version: 1.0.0\n",
		"null then block":   "apiVersion: v1\nentries: null\n  a:\n  - version: 1.0.0\n",
		"late directive":    "---\n%YAML 1.2\napiVersion: v1\nentries:\n  a:\n  - version: 1.0.0\n",
	} {
		t.Run(name, func(t *testing.T) {
			var whole HelmRepositoryIndex

			wholeErr := yaml.Unmarshal([]byte(index), &whole)

			_, err := decodeIndex([]byte(index))
			if (err == nil) != (wholeErr == nil) {
				t.Fatalf("a small index must be judged as a whole decode judges it: got %v, whole decode %v", err, wholeErr)
			}

			if _, err := decodeIndex([]byte(index + paddingCharts())); err == nil {
				t.Fatal("a large index must be refused instead of decoded whole")
			}
		})
	}
}

func TestDecodeIndexAcceptsACommentedMarkerWhenLarge(t *testing.T) {
	got, err := decodeIndex([]byte("--- # helm\n" + testIndex + paddingCharts()))
	if err != nil {
		t.Fatalf("a document marker followed by a comment must be accepted, got %v", err)
	}
	if len(got.Entries["podinfo"]) != 3 {
		t.Fatalf("expected the 3 podinfo versions, got %d", len(got.Entries["podinfo"]))
	}
}
